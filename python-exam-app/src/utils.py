"""
utils.py
--------
受講者名をURLに乗せるための「難読化」処理をまとめたモジュールです。

【重要な注意点】
ここで使う Base64 は「暗号化」ではありません。
誰でも簡単に元の文字列に戻せる仕組みなので、本当に守りたい個人情報などを
このやり方でURLに載せるのは危険です。今回はあくまで、URLをパッと見ただけでは
名前が読めないようにする「心理的なプロテクト（ちょっとした目隠し）」として
使っている、という位置づけです。
"""

# Python標準ライブラリの base64 モジュールをインポートします。
# 標準ライブラリとは、Pythonに最初から付属していて、pip installしなくても
# 使える便利な機能の集まりのことです。base64はその中の1つです。
import base64


def encode_name(name: str) -> str:
    """
    受講者の名前（文字列）をBase64形式の文字列にエンコードします。

    処理の流れ:
    1. 文字列(str)は人間が読める文字の並びですが、
       コンピュータ内部やURLで安全に扱うためには「バイト列(bytes)」に変換する必要があります。
       そのため、まず name.encode("utf-8") でバイト列に変換します。
    2. base64.urlsafe_b64encode() で、URLに含めても問題が起きない形式のBase64文字列に変換します。
       （通常のBase64は「+」や「/」を含むことがあり、URLの中でうまく扱えない場合があるためです）
    3. 最後に .decode("utf-8") で、バイト列を再び文字列(str)に戻して返します。
    """
    # str型の文字列は、そのままではbase64の関数に渡せません。
    # .encode("utf-8") を使って、コンピュータが扱いやすい「バイト列(bytes型)」に変換します。
    # 例: "太郎" のような文字列が b'\xe5\xa4\xaa\xe9...' のようなバイトの並びになる、というイメージです。
    name_bytes = name.encode("utf-8")

    # バイト列を、URLに含めても安全なBase64文字列（のバイト列）に変換します。
    # 戻り値もまだbytes型なので、この時点では encoded_bytes = b'44Kz...' のような形です。
    encoded_bytes = base64.urlsafe_b64encode(name_bytes)

    # 最後に .decode("utf-8") で bytes型 から str型 に戻します。
    # ここまでの処理で「name(str)」→「バイト列」→「Base64のバイト列」→「Base64の文字列」
    # という変換をしたことになります。
    return encoded_bytes.decode("utf-8")


def decode_name(encoded: str) -> str | None:
    """
    encode_name() で難読化された文字列を、元の名前(文字列)に復元します。

    URLパラメータは利用者が自由に書き換えられる場所なので、
    「Base64として正しくない値」や「デコードしても意味不明な値」が
    渡ってくる可能性があります。そのまま処理すると例外(エラー)が発生して
    アプリ全体が落ちてしまうため、try-exceptで例外を捕まえて、
    失敗したときは None を返すようにしています。
    呼び出す側では「Noneが返ってきたら、不正なURLとみなして認証画面に戻す」
    という使い方を想定しています。

    戻り値の型が「str | None」となっているのは、「正常に処理できれば文字列(str)を、
    失敗すれば None を返す関数です」という意味を表しています。
    """
    # try ブロックの中で、失敗するかもしれない処理をまとめて実行します。
    # 「失敗するかもしれない処理」とは、ここでは「URLから受け取った文字列を
    # Base64としてデコードする」という処理のことです。
    try:
        # encoded(str)を一度バイト列に変換してから、
        # base64.urlsafe_b64decode() でBase64をデコードします。
        # 渡された文字列がBase64として不正な形式だと、ここで例外が発生します。
        decoded_bytes = base64.urlsafe_b64decode(encoded.encode("utf-8"))

        # デコードできたバイト列を、UTF-8として文字列(str)に変換して返します。
        # バイト列の中身がUTF-8として解釈できない場合も、ここで例外が発生します。
        return decoded_bytes.decode("utf-8")
    except Exception:
        # Base64として不正な文字列だった場合や、UTF-8として解釈できない
        # バイト列だった場合など、どんな理由であれ「デコードに失敗したら」
        # ここでまとめてキャッチし、呼び出し元にはNoneだけを返します。
        #
        # 「なぜtry-exceptが必要なのか」という点も補足しておきます。
        # URLのuserパラメータは、悪意の有無にかかわらず利用者が自由に書き換えられます。
        # もしtry-exceptを書かずに例外が発生すると、Streamlitアプリ全体が
        # エラー画面になってしまいます。try-exceptで例外を「予測される失敗」として
        # 先回りして処理しておくことで、アプリを止めずに「認証画面に戻す」という
        # 想定通りの動きにつなげることができます。これが「防御的プログラミング」の一例です。
        return None
